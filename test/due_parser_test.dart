import 'package:flutter_test/flutter_test.dart';
import 'package:notimemo/utils/due_parser.dart';

// 기준: 2026-10-01 목요일 11:12 (10/2 금, 10/3 토, 10/4 일, 10/5 월, 10/7 수)
final now = DateTime(2026, 10, 1, 11, 12);

/// memo를 파싱해 결과를 'YYYY-MM-DD HH:mm' 문자열로(없으면 null) 돌려준다.
String? due(String memo, {DateTime? at}) {
  final r = parseDue(memo, at ?? now);
  if (r == null) return null;
  String p(int n) => n.toString().padLeft(2, '0');
  final d = r.at;
  return '${d.year}-${p(d.month)}-${p(d.day)} ${p(d.hour)}:${p(d.minute)}';
}

void main() {
  test('기준 날짜의 요일이 맞는지 확인', () {
    expect(now.weekday, DateTime.thursday);
    expect(DateTime(2026, 10, 5).weekday, DateTime.monday);
  });

  group('상대 날짜 + 시각', () {
    test('내일 3시는 오후 3시', () => expect(due('내일 3시에 치과 예약'), '2026-10-02 15:00'));
    test(
      '내일 아침 8시',
      () => expect(due('내일 아침 8시 수학 숙제 제출'), '2026-10-02 08:00'),
    );
    test('모레 저녁 6시', () => expect(due('모레 저녁 6시 가족 외식'), '2026-10-03 18:00'));
    test('내일모레는 모레', () => expect(due('내일모레 오후 2시'), '2026-10-03 14:00'));
    test('글피', () => expect(due('글피 오전 10시'), '2026-10-04 10:00'));
    test(
      '3일 뒤 오전 10시',
      () => expect(due('3일 뒤 오전 10시 학원 등록'), '2026-10-04 10:00'),
    );
    test('일주일 뒤', () => expect(due('일주일 뒤 오후 4시'), '2026-10-08 16:00'));
    test('2주 후', () => expect(due('2주 후 오전 9시'), '2026-10-15 09:00'));
    test('오늘 밤 10시', () => expect(due('오늘 밤 10시 약 먹기'), '2026-10-01 22:00'));
    test('붙여 써도 인식', () => expect(due('내일오후3시30분 미팅'), '2026-10-02 15:30'));
    test('3시 반', () => expect(due('내일 3시 반 병원'), '2026-10-02 15:30'));
  });

  group('요일', () {
    test('요일만 말하면 가장 가까운 미래', () {
      expect(due('금요일 오후 4시 동아리 회의'), '2026-10-02 16:00');
      expect(due('토요일 점심 12시 친구 약속'), '2026-10-03 12:00');
    });
    test('오늘과 같은 요일: 시각이 남았으면 오늘, 지났으면 다음 주', () {
      expect(due('목요일 오후 5시 보충수업'), '2026-10-01 17:00');
      expect(due('목요일 오전 9시 보충수업'), '2026-10-08 09:00');
    });
    test('다음주 X요일은 다음 주(월~일)의 그 요일', () {
      expect(due('다음주 월요일 오전 9시 영어 수행평가 준비물 챙기기'), '2026-10-05 09:00');
      expect(due('다음주 수요일 3시 치과'), '2026-10-07 15:00');
      expect(due('다음 주 일요일 오전 10시'), '2026-10-11 10:00');
      expect(due('담주 월요일 9시'), '2026-10-05 09:00');
      expect(due('다다음주 월요일 오전 9시'), '2026-10-12 09:00');
    });
    test('이번주 X요일: 아직 안 지났으면 그 날, 지났으면 없음', () {
      expect(due('이번주 일요일 오후 1시'), '2026-10-04 13:00');
      expect(due('이번주 금요일 오후 3시'), '2026-10-02 15:00');
      expect(due('이번주 월요일 오전 9시'), isNull);
    });
    test('요일 약어 욜, 주말', () {
      expect(due('금욜 오후 7시 모임'), '2026-10-02 19:00');
      expect(due('이번 주말 오전 10시 청소'), '2026-10-03 10:00');
    });
    test('시각 없이 요일만: 오전 9시로 채움', () {
      final r = parseDue('금요일까지 보고서 제출', now)!;
      expect(r.at, DateTime(2026, 10, 2, 9));
      expect(r.hasTime, isFalse);
    });
  });

  group('날짜 지정', () {
    test('월 일', () => expect(due('10월 15일 오후 2시 면접'), '2026-10-15 14:00'));
    test('지난 월 일은 내년', () => expect(due('1월 3일 시험'), '2027-01-03 09:00'));
    test('연도 명시', () => expect(due('2027년 3월 5일 오후 1시'), '2027-03-05 13:00'));
    test('슬래시 날짜', () => expect(due('10/15 오후 2시 면접'), '2026-10-15 14:00'));
    test('일만: 이번 달', () => expect(due('15일 오후 3시 납부'), '2026-10-15 15:00'));
    test(
      '일만: 지났으면 다음 달',
      () => expect(due('1일 오전 10시 월세'), '2026-11-01 10:00'),
    );
    test('존재하지 않는 날짜는 없음', () {
      expect(due('2월 30일 오후 3시'), isNull);
      expect(due('13월 5일'), isNull);
    });
    test('연말을 넘기는 다음 달', () {
      expect(
        due('1일 오전 10시 월세', at: DateTime(2026, 12, 20, 9)),
        '2027-01-01 10:00',
      );
    });
  });

  group('시각만 있는 경우', () {
    test(
      '오후 시각이 아직 안 지났으면 오늘',
      () => expect(due('오후 3시에 전화하기'), '2026-10-01 15:00'),
    );
    test('지났으면 내일', () => expect(due('오전 9시에 전화하기'), '2026-10-02 09:00'));
    test('24시간제', () => expect(due('18:30 저녁 약속'), '2026-10-01 18:30'));
    test('3시 반', () => expect(due('3시 반에 알려줘'), '2026-10-01 15:30'));
    test('새벽 2시는 내일', () => expect(due('새벽 2시 기상'), '2026-10-02 02:00'));
    test('밤 12시는 다음 날 0시', () => expect(due('밤 12시 알람'), '2026-10-02 00:00'));
    test('오늘 밤 12시', () => expect(due('오늘 밤 12시'), '2026-10-02 00:00'));
    test('자정', () => expect(due('자정에 제출'), '2026-10-02 00:00'));
    test('정오', () => expect(due('내일 정오에 만나기'), '2026-10-02 12:00'));
    test('오전 12시는 0시, 오후 12시는 정오', () {
      expect(due('내일 오전 12시'), '2026-10-02 00:00');
      expect(due('내일 오후 12시'), '2026-10-02 12:00');
    });
  });

  group('애매한 시각(7~11시, 표시 없음)', () {
    test('다른 날이면 오전', () => expect(due('내일 7시 기상'), '2026-10-02 07:00'));
    test('오늘이고 오전이 지났으면 오후로', () => expect(due('7시 기상'), '2026-10-01 19:00'));
    test('오늘이고 오전이 남았으면 오전', () {
      expect(due('7시 기상', at: DateTime(2026, 10, 1, 6, 0)), '2026-10-01 07:00');
    });
  });

  group('시간대 단어만', () {
    test('날짜와 함께면 기본 시각', () {
      expect(due('내일 점심 약속'), '2026-10-02 12:00');
      expect(due('내일 저녁 약속'), '2026-10-02 18:00');
    });
    test('날짜 없이 시간대 단어만 있으면 없음', () {
      expect(due('저녁 반찬 고민'), isNull);
      expect(due('아침 운동 계획 세우기'), isNull);
    });
  });

  group('상대 시간', () {
    test('30분 뒤', () => expect(due('30분 뒤에 알려줘'), '2026-10-01 11:42'));
    test('2시간 후', () => expect(due('2시간 후 회의'), '2026-10-01 13:12'));
    test('1시간 30분 뒤', () => expect(due('1시간 30분 뒤 회의'), '2026-10-01 12:42'));
    test('0분 뒤 같은 값은 무시', () => expect(due('0분 뒤'), isNull));
  });

  group('날짜만 있고 과거인 경우', () {
    test('오늘 + 지난 시각은 없음', () => expect(due('오늘 오전 9시 제출'), isNull));
    test(
      '오늘까지(시각 없음)는 오전 9시가 이미 지나 없음',
      () => expect(due('오늘까지 수학 숙제'), isNull),
    );
    test(
      '내일까지(시각 없음)는 내일 오전 9시',
      () => expect(due('내일까지 보고서 제출'), '2026-10-02 09:00'),
    );
  });

  group('반복 일정은 제안하지 않음', () {
    for (final memo in ['매주 월요일 운동', '매일 오전 7시 약 먹기', '매달 15일 납부']) {
      test('"$memo"는 없음', () => expect(due(memo), isNull));
    }
  });

  group('오탐 방지: 시각이 아닌 숫자', () {
    for (final memo in [
      '수학 문제집 30쪽 풀기',
      '3시간 공부하기',
      '30분 운동하기',
      '5000원 갚기',
      '영어 단어 100개 외우기',
      '엄마 생신 선물 사기',
      '휴대폰 요금 이번달 안에 납부',
      '레시피 1/2컵 설탕',
      '계란 우유 식빵 사오기',
      '방 청소하기',
      '',
    ]) {
      test('"$memo"는 없음', () => expect(due(memo), isNull));
    }
  });

  test('결과는 항상 기준 시각보다 미래', () {
    for (final memo in [
      '내일 3시',
      '금요일 오후 4시',
      '목요일 오전 9시',
      '1월 3일',
      '1일 오전 10시',
      '오후 3시',
      '오전 9시',
      '7시 기상',
    ]) {
      final r = parseDue(memo, now);
      expect(r == null || r.at.isAfter(now), isTrue, reason: memo);
    }
  });
}
